HEADER = """# PowerPoint Copilot 固定コンテンツ — Project{pid}

Copilot への指示用固定文言です。再生成しても本ファイルは上書きされません。
各スライドの箇条書きは **一字一句そのまま** pptx に転記してください。

## フォーマット

- `### スライドN: タイトル` — タイトルは JSON の slideMap と一致させる
- `**箇条書き（そのまま転記）:**` — 3行以上必須
- 図形・表・メディアの配置は Copilot MD の「試験用レイアウト仕様」に従う（本ファイルには書かない）

---

"""


def render_set(set_no: int, slides: list[dict], bullets_bank: list[list[list[str]]]) -> str:
    lines = [f"## セット{set_no}", ""]
    for slide in slides:
        no = slide["slideNo"]
        title = slide["title"]
        idx = no - 1
        variant = set_no - 1
        bullets = bullets_bank[idx][variant]
        lines += [
            f"### スライド{no}: {title}",
            "**箇条書き（そのまま転記）:**",
            *[f"- {b}" for b in bullets],
            "",
        ]
    return "\n".join(lines)


def write_project(pid: int) -> None:
    json_path = BASE / "類題Json" / f"MOS_PowerPoint類題_project{pid}_配置別_5セット_問題文.json"
    data = json.loads(json_path.read_text(encoding="utf-8"))
    bank = PROJECT_BULLETS[pid]
    parts = [HEADER.format(pid=pid)]
    for s in data["sets"]:
        sm = s["contentBlocks"]["slideMap"]
        parts.append(render_set(s["setNo"], sm, bank))
        parts.append("---")
        parts.append("")
    out = BASE / f"PowerPoint_類題_Copilot_Content_project{pid}.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out.name}")


def main() -> None:
    pids = [int(a) for a in sys.argv[1:]] if len(sys.argv) > 1 else [7, 8, 9, 10]
    for pid in pids:
        write_project(pid)


if __name__ == "__main__":
    main()
